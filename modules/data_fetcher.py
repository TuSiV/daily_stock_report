    def _batch_get_stock_names(self, codes):
        """批量获取股票名称"""
        names = {}
        if not codes:
            return names

        # 1. 优先尝试东方财富
        try:
            secids = []
            for code in codes:
                if code.startswith('6'):
                    secids.append(f'1.{code}')
                else:
                    secids.append(f'0.{code}')

            batch_size = 50
            for i in range(0, len(secids), batch_size):
                batch = secids[i:i+batch_size]
                secids_str = ','.join(batch)
                url = f'https://push2.eastmoney.com/api/qt/ulist/get?secids={secids_str}&fields=f12,f14'
                resp = self._safe_get(url)
                if resp:
                    data = resp.json()
                    if data.get('data') and data['data'].get('diff'):
                        for item in data['data']['diff']:
                            code = item.get('f12', '')
                            name = item.get('f14', '')
                            if code and name:
                                names[code] = name
        except Exception as e:
            print(f'Batch get stock names error: {e}')

        # 2. 如果东方财富失败或结果不全，用baostock补充
        missing = [c for c in codes if c not in names]
        if missing and HAS_BAOSTOCK:
            try:
                import baostock as bs
                bs.login()
                for code in missing:
                    if code.startswith('6'):
                        bs_code = f'sh.{code}'
                    else:
                        bs_code = f'sz.{code}'
                    rs = bs.query_stock_basic(code=bs_code)
                    while rs.error_code == '0' and rs.next():
                        row = rs.get_row_data()
                        # fields: code, code_name, ipoDate, outDate, type, status
                        if len(row) >= 2 and row[1]:
                            names[code] = row[1]
                bs.logout()
                print(f'baostock stock names: got {len([c for c in missing if c in names])} names')
            except Exception as e:
                print(f'baostock stock names error: {e}')

        return names
    
