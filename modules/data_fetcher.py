    def _get_title_hash(self, title, keywords):
        """Generate a hash for deduplication based on full title"""
        import hashlib
        # Normalize title
        normalized = title.lower().replace(' ', '').replace('\u3000', '')
        # 使用完整标题计算hash，避免截断导致的误判
        return hashlib.md5(normalized.encode()).hexdigest()[:16]

