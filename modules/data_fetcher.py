        self._fetch_commodity_eastmoney(result)
        
        # 2. 对于失败的商品，尝试新浪财经备用
        for key in ['gold', 'wti', 'brent']:
            if key not in result or result.get(key, {}).get('need_ai'):
                print(f'Eastmoney {key} failed, trying Sina fallback...')
                self._fetch_commodity_sina(result, key)
        
        return result
    
